// The whole Org Handbook as one file: a self-contained HTML page (diagrams
// as inline SVG, ready to share or print to PDF) or Markdown with Mermaid
// (GitHub, Azure DevOps, Notion, Confluence with a Mermaid macro). Pure.
import {flowStory, simpleFlowDiagram} from "./flow-story.js";
import {layoutGraph} from "./diagram-layout.js";
import {diagramSvg, legendKinds} from "./diagram-svg.js";
import {toMermaid, GUIDE_TYPES} from "./org-guide.js";
import {an} from "./handbook.js";

const lc = s => String(s || "").toLowerCase();
const hEsc = s => String(s == null ? "" : s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const mdEsc = s => String(s == null ? "" : s).replace(/[|*_`[\]<>]/g, c => "\\" + c);
const anchor = id => "h-" + String(id).replace(/[^a-z0-9]+/gi, "-").toLowerCase();
const stages = p => p.columns.filter(c => !c.id.startsWith("@")).map(c => c.label);
const colLabel = c => (c.id === "@any" ? "Any change" : c.id === "@create" ? "Created" : c.label);

function flowsWithMeta(hb, items) {
  const byId = new Map((items && items.flows || []).map(f => [`flow:${lc(f.name)}`, f]));
  return hb.flows.map(f => ({f, meta: (byId.get(f.id) || {}).meta || null}));
}

// Lines of a story (shared by both formats).
function storyLines(story) {
  const out = [];
  for (const s of story.steps) {
    const sub = [];
    for (const b of s.branches) sub.push(`${b.label}${b.when ? ` (${b.when})` : ""} → ${b.to}`);
    if (s.then) sub.push(`then → ${s.then === "the end" ? "done" : s.then}`);
    if (s.fault) sub.push(`if it fails → ${s.fault}`);
    out.push({n: s.n, text: `${s.icon} ${s.text}${s.person ? " (a person does this)" : ""}`, sub});
  }
  return out;
}

// ── Markdown ───────────────────────────────────────────────────────────
export function handbookToMarkdown(hb, items, {eli5 = {}} = {}) {
  const out = [`# Org Handbook${hb.orgName ? `: ${mdEsc(hb.orgName)}` : ""}`, "",
    `_Generated by SaralForce on ${new Date(hb.builtAt).toISOString().slice(0, 10)}. Read-only notes on how this org works._`, ""];
  out.push("## Contents", "", "- [How the business works](#how-the-business-works)", "- [Start here](#start-here)",
    "- [Departments](#departments)", "- [Business processes](#business-processes)", "- [Flows](#flows)", "- [Glossary](#glossary)", "");
  out.push("## How the business works", "", hb.business || "_No AI summary yet._", "");
  if (hb.startHere.length) out.push("## Start here", "", ...hb.startHere.map((s, i) => `${i + 1}. ${s.text}`), "");
  if (hb.departments.length) {
    out.push("## Departments", "");
    for (const d of hb.departments) out.push(`- **${mdEsc(d.label)}**${d.description ? `: ${mdEsc(d.description)}` : ""}: ${d.objects.map(o => mdEsc(o.label)).join(", ")}`);
    out.push("");
  }
  out.push("## Business processes", "");
  for (const p of hb.processes) {
    out.push(`### The life of ${an(p.label)} ${mdEsc(p.label)}`, "");
    if (stages(p).length) out.push(`**${mdEsc(p.stageField.label)}:** ${stages(p).map(mdEsc).join(" → ")}`, "");
    if (p.lanes.length) {
      out.push(`| When | ${p.columns.map(colLabel).map(mdEsc).join(" | ")} |`, `|---|${p.columns.map(() => "---").join("|")}|`);
      for (const l of p.lanes) out.push(`| **${l.label}** | ${p.columns.map(c => (l.cells[c.id] || []).map(x => mdEsc(x.label)).join("<br>")).join(" | ")} |`);
      out.push("");
    }
    for (const m of p.moves) out.push(`- ${mdEsc(m.by.label)} sets ${mdEsc(p.stageField.label)} to **${mdEsc(m.to)}**`);
    if (p.moves.length) out.push("");
  }
  out.push("## Flows", "");
  for (const {f, meta} of flowsWithMeta(hb, items)) {
    out.push(`### ${mdEsc(f.label)}`, "", `_${mdEsc(f.kindLabel)}${f.timing ? ` · ${f.timing}` : ""} · \`${f.name}\`_`, "", mdEsc(f.summary), "");
    if (!meta) continue;
    const story = flowStory(meta);
    out.push(`**When:** ${mdEsc(story.when)}`, "", "```mermaid", toMermaid(simpleFlowDiagram(meta)), "```", "");
    out.push("**Step by step**", "");
    for (const s of storyLines(story)) {
      out.push(`${s.n}. ${mdEsc(s.text)}`);
      for (const x of s.sub) out.push(`   - ${mdEsc(x)}`);
    }
    if (eli5[f.id]) out.push("", `> 🧸 ${mdEsc(eli5[f.id].eli5)}`);
    out.push("");
  }
  out.push("## Glossary", "");
  for (const g of hb.glossary) {
    out.push(`### ${mdEsc(g.label)} (\`${g.name}\`)`, "");
    if (g.recordTypes.length) out.push(`- **Kinds:** ${g.recordTypes.map(mdEsc).join(", ")}`);
    for (const p of g.picklists) out.push(`- **${mdEsc(p.label)}:** ${p.values.map(mdEsc).join(" · ")}`);
    out.push("");
  }
  return out.join("\n");
}

// ── HTML ───────────────────────────────────────────────────────────────
function svgBlock(g, title) {
  if (!g || !g.nodes.length) return "";
  const layout = layoutGraph(g, {dir: g.dir || "TB"});
  const legend = legendKinds(layout).map(k => `<span class="lg"><i style="background:${k.colors.light[0]};border-color:${k.colors.light[1]}"></i>${hEsc(k.label)}</span>`).join("");
  return `<div class="dg">${diagramSvg(layout, {title})}</div><div class="legend">${legend}</div>`;
}

export function handbookToHtml(hb, items, {eli5 = {}} = {}) {
  const P = [];
  P.push(`<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Org Handbook${hb.orgName ? ": " + hEsc(hb.orgName) : ""}</title><style>
body{font:14px/1.6 "Segoe UI",Helvetica,Arial,sans-serif;color:#1f2532;margin:0;background:#f6f7f9}
main{max-width:1100px;margin:0 auto;padding:28px 26px;background:#fff}
h1{margin:0 0 4px}h2{margin:38px 0 12px;border-bottom:2px solid #e3e6ec;padding-bottom:6px}h3{margin:26px 0 6px}
.meta{color:#6b7385}.toc a{margin-right:14px}.card{border:1px solid #e3e6ec;border-radius:10px;padding:12px 16px;margin:12px 0}
.dg{overflow:auto;border:1px solid #e3e6ec;border-radius:8px;padding:8px;background:#fbfcfd;max-width:100%}
.legend{display:flex;flex-wrap:wrap;gap:10px;font-size:12px;color:#4b5466;margin:6px 0 10px}.lg i{display:inline-block;width:12px;height:12px;border:1.5px solid;border-radius:3px;margin-right:4px;vertical-align:-2px}
.when{background:#e9f7ef;color:#11482a;border-radius:8px;padding:8px 12px}
.stages span{display:inline-block;background:#e9f7ef;border:1px solid #b9e3c9;color:#11482a;border-radius:10px;padding:1px 9px;margin:2px;font-size:12.5px;font-weight:600}
table{border-collapse:collapse;width:100%;font-size:13px}td,th{border:1px solid #e3e6ec;padding:6px 8px;text-align:left;vertical-align:top}th{background:#f3f5fa}
ol.story li{margin:3px 0}ol.story ul{margin:2px 0 4px;color:#4b5466;font-size:13px}
.eli5{background:#fff7e0;border:1px solid #f0d78c;border-radius:8px;padding:8px 12px;margin-top:8px}
pre{white-space:pre-wrap;font:inherit;background:#f6f7f9;padding:10px 12px;border-radius:8px}
@media print{body{background:#fff}main{padding:0}.card,.dg{break-inside:avoid}}
</style></head><body><main>`);
  P.push(`<h1>Org Handbook${hb.orgName ? `: ${hEsc(hb.orgName)}` : ""}</h1><div class="meta">Generated by SaralForce on ${hEsc(new Date(hb.builtAt).toISOString().slice(0, 10))} · read-only notes on how this org works</div>`);
  P.push(`<p class="toc"><a href="#business">How the business works</a><a href="#start">Start here</a><a href="#depts">Departments</a><a href="#processes">Business processes</a><a href="#flows">Flows (${hb.flows.length})</a><a href="#glossary">Glossary</a></p>`);
  P.push(`<h2 id="business">How the business works</h2>${hb.business ? `<pre>${hEsc(hb.business)}</pre>` : `<p class="meta">No AI summary yet.</p>`}`);
  if (hb.startHere.length) P.push(`<h2 id="start">Start here</h2><ol>${hb.startHere.map(s => `<li>${hEsc(s.text)}</li>`).join("")}</ol>`);
  if (hb.departments.length) {
    P.push(`<h2 id="depts">Departments</h2>${hb.departments.map(d => `<div class="card"><b>${hEsc(d.label)}</b>${d.description ? ` <span class="meta">${hEsc(d.description)}</span>` : ""}<br>${d.objects.map(o => hEsc(o.label)).join(" · ")}</div>`).join("")}`);
  }
  P.push(`<h2 id="processes">Business processes</h2>`);
  for (const p of hb.processes) {
    P.push(`<div class="card" id="${anchor("process:" + p.object)}"><h3>The life of ${an(p.label)} ${hEsc(p.label)}</h3>`);
    if (stages(p).length) P.push(`<div class="stages">${stages(p).map(s => `<span>${hEsc(s)}</span>`).join(" → ")}</div>`);
    if (p.lanes.length) {
      P.push(`<table><tr><th>When</th>${p.columns.map(c => `<th>${hEsc(colLabel(c))}${p.moves.filter(m => m.to === c.id).map(m => `<div class="meta">set by ${hEsc(m.by.label)}</div>`).join("")}</th>`).join("")}</tr>`);
      for (const l of p.lanes) P.push(`<tr><th>${hEsc(l.label)}<div class="meta">${hEsc(l.hint)}</div></th>${p.columns.map(c => `<td>${(l.cells[c.id] || []).map(x => hEsc(x.label)).join("<br>")}</td>`).join("")}</tr>`);
      P.push("</table>");
    } else P.push(`<p class="meta">Nothing runs automatically on it.</p>`);
    P.push("</div>");
  }
  P.push(`<h2 id="flows">Flows</h2>`);
  for (const {f, meta} of flowsWithMeta(hb, items)) {
    P.push(`<div class="card" id="${anchor(f.id)}"><h3>${hEsc(f.label)}</h3><div class="meta">${hEsc(f.kindLabel)}${f.timing ? ` · ${hEsc(f.timing)}` : ""} · ${hEsc(f.name)}</div><p>${hEsc(f.summary)}</p>`);
    if (meta) {
      const story = flowStory(meta);
      P.push(`<div class="when">▶ ${hEsc(story.when)}</div>`, svgBlock(simpleFlowDiagram(meta), f.label));
      P.push(`<ol class="story">${storyLines(story).map(s => `<li>${hEsc(s.text)}${s.sub.length ? `<ul>${s.sub.map(x => `<li>${hEsc(x)}</li>`).join("")}</ul>` : ""}</li>`).join("")}</ol>`);
      if (eli5[f.id]) P.push(`<div class="eli5">🧸 ${hEsc(eli5[f.id].eli5)}</div>`);
    }
    P.push("</div>");
  }
  P.push(`<h2 id="glossary">Glossary</h2>`);
  for (const g of hb.glossary) {
    P.push(`<div class="card"><b>${hEsc(g.label)}</b> <span class="meta">${hEsc(g.name)}</span>${g.recordTypes.length ? `<div><b>Kinds:</b> ${g.recordTypes.map(hEsc).join(", ")}</div>` : ""}` +
      `${g.picklists.map(p => `<div><b>${hEsc(p.label)}:</b> ${p.values.map(hEsc).join(" · ")}</div>`).join("")}</div>`);
  }
  P.push(`<p class="meta">Counts: ${Object.entries(hb.counts).filter(([k]) => GUIDE_TYPES[k]).map(([k, v]) => `${v} ${GUIDE_TYPES[k].plural}`).join(" · ")}</p>`);
  P.push("</main></body></html>");
  return P.join("\n");
}
